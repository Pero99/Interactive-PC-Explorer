const TRANSLATED_DB_MAP: Record<
  Exclude<Locale, 'de'>,
  Record<PCComponentId, TranslatedComponentContent>
> = {
  en: EN_HARDWARE,
  tr: TR_HARDWARE,
  ro: RO_HARDWARE,
  ar: AR_HARDWARE,
};

export function getLocalizedHardwareDb(
  locale: Locale
): Record<PCComponentId, HardwareComponentData> {
  if (locale === 'de') return HARDWARE_DB;

  const trMap = TRANSLATED_DB_MAP[locale];
  const result = {} as Record<PCComponentId, HardwareComponentData>;

  (Object.keys(HARDWARE_DB) as PCComponentId[]).forEach((id) => {
    const base = HARDWARE_DB[id];
    const tr = trMap[id];
    if (!tr) {
      result[id] = base;
    } else {
      result[id] = {
        ...base,
        name: tr.name,
        shortName: tr.shortName,
        short: tr.short,
        category: (UI_TRANSLATIONS[locale].categories[base.category] ||
          base.category) as ComponentCategory,
        desc: tr.desc,
        tasks: tr.tasks,
        specs: tr.specs,
        coop: tr.coop,
        missing: tr.missing,
        usecases: tr.usecases,
      };
    }
  });

  return result;
}

export function getLocalizedComponentList(
  locale: Locale
): HardwareComponentData[] {
  const db = getLocalizedHardwareDb(locale);
  return Object.values(db);
}
